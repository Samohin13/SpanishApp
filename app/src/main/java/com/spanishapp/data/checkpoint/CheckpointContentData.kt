 * Каждый сценарий привязан к ID урока в курсе (u1_l14, u5_l5, u16_l14, etc.) —
 * это означает что в указанном «уроке» вместо упражнений запускается checkpoint.
 *
 * Phase 1 курса v1.2.0: все 21 сценария наполнены реальным контентом.
 * Длинные сценарии (15-20 мин): по 18 актов в 3 сценах.
 * Мини-тесты (8 мин): 6 актов в 1 сцене.
 */
object CheckpointContentData {

    fun byId(id: String): CheckpointContent? = ALL[id]
    fun all(): List<CheckpointContent> = ALL.values.toList()
    fun forBlock(blockId: String): List<CheckpointContent> =
        ALL.values.filter { it.blockId == blockId }

    /** Helper для краткого создания PICK_PHRASE акта. */
    private fun pick(narration: String, npc: String = "", npcLine: String = "",
                     npcRu: String = "",
                     options: List<Triple<String, String, Boolean>>,
                     hint: String = "", expl: String = "") =
        CheckpointAct(
            type = CheckpointActType.PICK_PHRASE,
            narration = narration, npcSpeaker = npc, npcLine = npcLine,
            npcTranslation = npcRu,
            options = options.map { (es, ru, isCorrect) ->
                CheckpointOption(es, ru, isCorrect)
            },
            hint = hint, explanation = expl,
        )

    /** Helper для SAY_OUT_LOUD (произнести). */
    private fun say(narration: String, expected: String, hint: String = "", expl: String = "") =
        CheckpointAct(type = CheckpointActType.SAY_OUT_LOUD,
            narration = narration, expectedReply = expected, hint = hint, explanation = expl)

    /** Helper для TYPE_REPLY (напечатать). */
    private fun type(narration: String, expected: String, hint: String = "", expl: String = "") =
        CheckpointAct(type = CheckpointActType.TYPE_REPLY,
            narration = narration, expectedReply = expected, hint = hint, explanation = expl)

    /** Helper для LISTEN_AND_PICK (услышать + выбрать). */
    private fun listen(narration: String, audioLine: String, audioRu: String = "",
                       options: List<Triple<String, String, Boolean>>,
                       expl: String = "") =
        CheckpointAct(type = CheckpointActType.LISTEN_AND_PICK,
            narration = narration, npcLine = audioLine, npcTranslation = audioRu,
            options = options.map { (es, ru, c) -> CheckpointOption(es, ru, c) },
            explanation = expl)

    /** Helper для BUILD_REPLY (собрать из тайлов). */
    private fun build(narration: String, expected: String, tokens: List<String>, expl: String = "") =
        CheckpointAct(type = CheckpointActType.BUILD_REPLY,
            narration = narration, expectedReply = expected, replyTokens = tokens, explanation = expl)

    /** Helper для NARRATION_ONLY. */
    private fun narr(text: String, npc: String = "", npcLine: String = "", npcRu: String = "") =
        CheckpointAct(type = CheckpointActType.NARRATION_ONLY,
            narration = text, npcSpeaker = npc, npcLine = npcLine, npcTranslation = npcRu)

    private fun scene(title: String, setting: String, vararg acts: CheckpointAct) =
        CheckpointScene(title, setting, acts.toList())

